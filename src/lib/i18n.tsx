export type Lang = "en" | "es";
const Ctx = createContext<{ lang: Lang; t: Dict; setLang: (l: Lang) => void }>({ lang: "en", t: en, setLang: () => {} });

export function LangProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>("en");
  useEffect(() => {
    const s = localStorage.getItem("fl-lang");
    if (s === "es" || s === "en") setLangState(s);
  }, []);
  useEffect(() => {
    document.documentElement.lang = lang;
  }, [lang]);
  const setLang = (l: Lang) => {
    setLangState(l);
    localStorage.setItem("fl-lang", l);
  };
  return <Ctx.Provider value={{ lang, t: lang === "es" ? es : en, setLang }}>{children}</Ctx.Provider>;
}

export const useI18n = () => useContext(Ctx);
